-- 0016: сводный канал входа считает ядро, а не берёт из CRM.
--
-- До 1.4.0 сводный канал приходил готовым полем CRM, а заполнял его внешний скрипт вручную: месяц без прогона
-- скрипта оставлял поле пустым, и правило отбора с проверкой по сводному каналу молча переставало отсекать
-- (первый инстанс, октябрь 2026: поле пусто у всех лидов месяца). Теперь ядро загружает входы правила и считает
-- значение само при каждой загрузке; поле CRM остаётся для сверки.
--
-- lead_source           — «источник» сделки со слов клиента, свободный текст CRM. Может содержать телефон —
--                         инстанс обязан объявить столбец в проверке телефонов внутри текста (К6).
-- entry_point_host      — только хост адреса точки входа: полный адрес с параметрами в факты не попадает.
-- entry_channel_derived — сводный канал, посчитанный ядром по правилу инстанса (первое сработавшее по приоритету).
--
-- Колонки только добавляются и повторно не падают (IF NOT EXISTS): код до 0016 продолжает читать и писать сделки.
ALTER TABLE facts.deal ADD COLUMN IF NOT EXISTS lead_source VARCHAR;
ALTER TABLE facts.deal ADD COLUMN IF NOT EXISTS entry_point_host VARCHAR;
ALTER TABLE facts.deal ADD COLUMN IF NOT EXISTS entry_channel_derived VARCHAR;
