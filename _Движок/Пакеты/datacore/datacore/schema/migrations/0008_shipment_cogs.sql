-- Этап 5. Себестоимость проданного.
--
-- Себестоимость лежит на отгрузке, а не на платеже: платёж — это деньги, а себестоимость — то, что уехало клиенту.
-- У одного заказа бывает несколько платежей (аванс и доплата), и делить между ними себестоимость по догадке
-- значило бы придумать число.
--
-- Связь с деньгами идёт через те же документы-посредники, что и в этапе 4: счёт покупателю и заказ. Живая
-- проверка первого инстанса: заказ есть лишь у малой части отгрузок, счёт — у большинства; вместе они
-- покрывают почти все. Привязка только к заказу оставила бы без себестоимости большую часть проданного.
--
-- Правило счёта подтверждено владельцем финансового контура 20.09.2026: «берётся средняя цена на основе последних
-- приёмок, а по услугам — из специального поля». Живая проверка 21.09.2026 показала, что готовый итог этого
-- механизма лежит в закупочной цене справочника: она заполнена у заметно большего числа позиций, чем цена
-- последней приёмки. Счёт по приёмкам оставлял без себестоимости втрое большую долю продаж и расходился со
-- справочником почти целиком за счёт этих непокрытых позиций, а не движения цен.
--
-- Сверка первого инстанса: доля себестоимости в выручке близка к финансовому отчёту, а сами суммы отличаются
-- в разы, потому что здесь все отгрузки, а финансовый отчёт считает только оплаченные счета —
-- это разные выборки при одном правиле, а не ошибка расчёта.
--
-- `positions_total` и `positions_priced` — сколько строк в отгрузке и у скольких известна закупочная цена. Без них
-- неполнота была бы невидимой: отгрузка, где цена известна у одной позиции из десяти, дала бы маленькое число,
-- неотличимое от честной низкой себестоимости.
DROP TABLE IF EXISTS facts.order_cogs;
CREATE TABLE facts.shipment_cogs (
  shipment_id VARCHAR NOT NULL,
  order_id VARCHAR,
  invoice_id VARCHAR,
  brand VARCHAR,
  shipped_at TIMESTAMP WITH TIME ZONE NOT NULL,
  cogs DECIMAL(18,2) NOT NULL,
  revenue_shipped DECIMAL(18,2) NOT NULL,
  positions_total INTEGER NOT NULL,
  positions_priced INTEGER NOT NULL,
  unpriced_revenue DECIMAL(18,2) NOT NULL,
  money_system VARCHAR NOT NULL,
  source_system VARCHAR NOT NULL,
  source_class VARCHAR NOT NULL CHECK (source_class IN ('A','B','C','D','E','F')),
  load_id VARCHAR NOT NULL,
  loaded_at TIMESTAMP WITH TIME ZONE NOT NULL,
  PRIMARY KEY (shipment_id, source_system),
  CONSTRAINT k5_cogs_not_future CHECK (shipped_at <= loaded_at)
);
