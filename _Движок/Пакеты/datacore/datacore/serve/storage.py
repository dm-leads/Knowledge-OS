"""Выбор адреса хранилища для команд и загрузчиков."""
from __future__ import annotations

import os


def storage_url(cfg, db=None) -> str:
    """Адрес хранилища: аргумент -> переменная окружения из конфигурации -> файл DuckDB.

    Переменная окружения обязательна для сервера: аргументы командной строки видны в списке процессов
    любому пользователю машины, и адрес вместе с паролем оттуда утекает (проверено 23.09.2026 —
    пароль рабочей базы пришлось отзывать). Аргумент оставлен для разработки и тестов.
    """
    if db:
        return db
    return os.environ.get(cfg.postgres_url_env) or f"duckdb:///{cfg.duckdb_path.as_posix()}"
